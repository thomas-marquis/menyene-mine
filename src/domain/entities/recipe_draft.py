from dataclasses import dataclass
from datetime import datetime
from enum import StrEnum
from typing import TypedDict

from .recipe import Recipe


class RecipeDraftContent(TypedDict, total=False):
    """TypedDict representing the structure of generated recipe draft content.

    This matches the frontend TypeScript RecipeDraftContent interface and
    represents the JSON structure stored in the database.
    """

    title: str | None
    summary: str | None
    ingredients: list[str] | None
    instructions: list[str] | None
    servings: int | None
    prep_time: str | None
    cook_time: str | None
    difficulty: str | None


class RecipeDraftStatus(StrEnum):
    """Status of a recipe draft."""

    DRAFT = "draft"
    VALIDATED = "validated"
    REJECTED = "rejected"


@dataclass
class RecipeDraft:
    """Domain entity for recipe drafts generated by AI."""

    id: int | None = None
    user_instruction: str | None = None
    generated_content: Recipe | RecipeDraftContent | None = None  # Structured recipe data or dict representation
    status: RecipeDraftStatus = RecipeDraftStatus.DRAFT
    created_at: datetime | None = None
    updated_at: datetime | None = None
    recipe_id: int | None = None  # Reference to the actual recipe if validated

    def get_content_dict(self) -> RecipeDraftContent:
        """
        Get generated_content as a dictionary.

        Returns:
            Dictionary representation of the generated content
        """
        if isinstance(self.generated_content, Recipe):
            return {
                "title": self.generated_content.title,
                "summary": self.generated_content.summary,
                "ingredients": self.generated_content.ingredients,
                "instructions": self.generated_content.instructions,
                "servings": self.generated_content.servings,
                "prep_time": self.generated_content.prep_time,
                "cook_time": self.generated_content.cook_time,
                "difficulty": self.generated_content.difficulty,
            }
        return self.generated_content or {}
